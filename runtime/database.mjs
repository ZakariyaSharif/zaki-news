import {neon} from '@neondatabase/serverless';

export function database(query) {
  return {prepare(sql) {
    return {bind(...params) {
      return {
        all: () => query(sql,params),
        first: async () => (await query(sql,params)).results[0] ?? null,
        run: () => query(sql,params)
      };
    }};
  }};
}

export function hostedDatabase(env) {
  const {D1_ACCOUNT_ID, D1_DATABASE_ID, D1_API_TOKEN} = env;
  if (!D1_ACCOUNT_ID || !D1_DATABASE_ID || !D1_API_TOKEN) throw Error('Configure the D1 connection');
  const endpoint = 'https://api.cloudflare.com/client/v4/accounts/'+encodeURIComponent(D1_ACCOUNT_ID)+'/d1/database/'+encodeURIComponent(D1_DATABASE_ID)+'/query';
  return database(async (sql,params) => {
    const response = await fetch(endpoint,{method:'POST',headers:{authorization:'Bearer '+D1_API_TOKEN,'content-type':'application/json'},body:JSON.stringify({sql,params})});
    if (!response.ok) throw Error('D1 request failed ('+response.status+')');
    const data = await response.json();
    if (!data.success || !data.result?.[0]?.success) throw Error('D1 query failed');
    return data.result[0];
  });
}

export function emptyDatabase() {
  return database(async () => ({results:[],meta:{changes:0}}));
}

export function postgresPlaceholders(sql) {
  let index = 0;
  return String(sql).replace(/\?/g, () => '$' + (++index));
}

export function sqliteToPostgres(sql) {
  let text = String(sql);
  const ignore = /^\s*INSERT\s+OR\s+IGNORE\s+/i.test(text);
  if (ignore) text = text.replace(/^\s*INSERT\s+OR\s+IGNORE\s+/i, 'INSERT ');
  text = text.replace(/json_extract\s*\(\s*([^,]+?)\s*,\s*'\$\.([^']+)'\s*\)/gi, "($1)::json->>'$2'");
  text = text.replace(/\bexcluded\./g, 'EXCLUDED.');
  if (ignore && !/\bON\s+CONFLICT\b/i.test(text)) text += ' ON CONFLICT DO NOTHING';
  return postgresPlaceholders(text);
}

const SCHEMA_SQL = [
  `CREATE TABLE IF NOT EXISTS articles (
    slug TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    summary TEXT NOT NULL,
    category TEXT NOT NULL,
    author TEXT NOT NULL,
    body TEXT NOT NULL,
    image TEXT NOT NULL,
    image_alt TEXT NOT NULL,
    seo_title TEXT NOT NULL DEFAULT '',
    seo_description TEXT NOT NULL DEFAULT '',
    language TEXT NOT NULL DEFAULT 'so',
    published_at TEXT,
    updated_at TEXT NOT NULL
  )`,
  `CREATE INDEX IF NOT EXISTS articles_published ON articles (published_at DESC)`,
  `CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS contacts (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at TEXT NOT NULL
  )`,
  `CREATE INDEX IF NOT EXISTS contacts_created_at ON contacts (created_at)`,
  `CREATE TABLE IF NOT EXISTS subscribers (
    email TEXT PRIMARY KEY,
    created_at TEXT NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS schedules (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    event_date TEXT NOT NULL,
    amount DOUBLE PRECISION,
    usd DOUBLE PRECISION,
    supply DOUBLE PRECISION,
    source TEXT NOT NULL,
    actual TEXT NOT NULL DEFAULT '',
    forecast TEXT NOT NULL DEFAULT '',
    previous TEXT NOT NULL DEFAULT '',
    importance TEXT NOT NULL DEFAULT '',
    release_time TEXT NOT NULL DEFAULT '',
    country TEXT NOT NULL DEFAULT ''
  )`,
  `CREATE INDEX IF NOT EXISTS schedules_date ON schedules (kind, event_date)`
];

function neonConnectionString(env) {
  return String(
    env.DATABASE_URL
    || env.DATABASE_URL_UNPOOLED
    || env.POSTGRES_URL
    || env.POSTGRES_URL_NON_POOLING
    || env.POSTGRES_PRISMA_URL
    || ''
  ).trim();
}

export function neonDatabase(env) {
  const connection = neonConnectionString(env);
  if (!connection) throw Error('Configure the Postgres connection');
  const sql = neon(connection, {fullResults: true});
  let ready;
  const ensure = () => {
    if (!ready) {
      ready = (async () => {
        for (const statement of SCHEMA_SQL) await sql.query(statement, []);
      })().catch(error => {
        ready = undefined;
        throw error;
      });
    }
    return ready;
  };
  return database(async (sqliteSql, params) => {
    await ensure();
    const text = sqliteToPostgres(sqliteSql);
    const result = await sql.query(text, params);
    const rows = Array.isArray(result?.rows) ? result.rows : (Array.isArray(result) ? result : []);
    const changes = Number(result?.rowCount ?? result?.changes ?? 0);
    return {results: rows, meta: {changes}};
  });
}

export function resolveDatabase(env) {
  if (env.D1_ACCOUNT_ID && env.D1_DATABASE_ID && env.D1_API_TOKEN) return hostedDatabase(env);
  if (neonConnectionString(env)) return neonDatabase(env);
  return emptyDatabase();
}
